/**
 * Step 8 — CODEOWNERS.
 * Prompts for team slugs (maintainers / sec-team / architects) and validates
 * them via gh api. Generates .github/CODEOWNERS for the target repo.
 */
import { confirm, input } from '@inquirer/prompts';
import { gh } from '../shell.mjs';
import { validateTeamSlug } from '../validators.mjs';

export const id = '08-codeowners';
export const title = 'CODEOWNERS';

export async function run(ctx) {
  const { preview, targetRepo, dry } = ctx;

  // Default maintainers to the current gh user — works for personal repos
  // where no org team exists. User can override by typing something else.
  let defaultMaintainer = '';
  try {
    const { ghWhoami } = await import('../shell.mjs');
    defaultMaintainer = await ghWhoami();
  } catch (err) {
    preview.warn(`could not derive gh whoami (non-fatal): ${err.message}`);
  }

  // allowEmpty=true so user can press Enter on an empty input to skip
  // CODEOWNERS entirely (e.g. personal disposable repos). Default is the
  // gh user's login so the common case is one Enter press.
  const maintainers = await promptTeam(
    'Maintainers team/login (Enter for default, blank to skip):',
    true,
    defaultMaintainer,
  );
  if (!maintainers) {
    preview.warn('skipping CODEOWNERS — no maintainers specified');
    return { status: 'skipped' };
  }
  const secTeam = await promptTeam('Security team/login (or blank):', true);
  const architects = await promptTeam('Architects team/login (or blank):', true);

  for (const slug of [maintainers, secTeam, architects].filter(Boolean)) {
    const r = await validateTeamExists(slug);
    if (!r.ok) preview.warn(`"${slug}" could not be verified: ${r.error}`);
    else preview.notice(`verified: ${slug}`);
  }

  const body = renderCodeowners({ maintainers, secTeam, architects });
  preview.info('Generated .github/CODEOWNERS:');
  console.log(body.split('\n').map((l) => `    ${l}`).join('\n'));

  if (dry) {
    preview.warn('(dry-run) skipping CODEOWNERS write');
    return { status: 'dry' };
  }
  const ok = await confirm({ message: `Stage .github/CODEOWNERS on ${targetRepo}?`, default: true });
  if (!ok) return { status: 'skipped' };

  // We do not write directly to the target repo from the wizard.
  // The generated body is handed back to the user to commit via the normal
  // Issue → PR pipeline (S7 dogfooding rule).
  ctx.artifacts = ctx.artifacts || {};
  ctx.artifacts.codeowners = body;
  preview.info('CODEOWNERS staged as artifact — commit it via Issue → PR pipeline.');
  return { status: 'ok' };
}

async function promptTeam(message, allowEmpty = false, defaultValue = '') {
  const v = await input({
    message,
    default: defaultValue || undefined,
    validate: (s) => {
      const trimmed = s.trim();
      if (allowEmpty && trimmed === '') return true;
      return validateTeamSlug(trimmed).ok || validateTeamSlug(trimmed).error;
    },
  });
  if (v.trim() === '') return '';
  return validateTeamSlug(v).value;
}

async function validateTeamExists(slug) {
  try {
    if (slug.includes('/')) {
      const [org, team] = slug.split('/');
      await gh(['api', `orgs/${org}/teams/${team}`], { silent: true });
    } else {
      await gh(['api', `users/${slug}`], { silent: true });
    }
    return { ok: true };
  } catch (err) {
    return { ok: false, error: (err.stderr || err.message || '').slice(0, 160) };
  }
}

export function renderCodeowners({ maintainers, secTeam, architects }) {
  const lines = [
    '# CODEOWNERS generated by setup wizard',
    '# Each row: path-pattern @owner',
    '',
    `* @${maintainers}`,
    '',
    '# security-sensitive paths',
  ];
  if (secTeam) lines.push(`/.github/workflows/ @${secTeam}`);
  if (secTeam) lines.push(`/.github/actions/ @${secTeam}`);
  if (secTeam) lines.push(`/docs/security.md @${secTeam}`);
  lines.push('');
  if (architects) {
    lines.push('# architecture review');
    lines.push(`/docs/architecture.md @${architects}`);
    lines.push('/CLAUDE.md @' + architects);
  }
  return lines.join('\n') + '\n';
}
