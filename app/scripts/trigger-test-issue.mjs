#!/usr/bin/env node
// Smoke test: create a test Issue in the deployed smoke repo and watch the
// triage workflow fire.
//
//   pnpm exec node scripts/trigger-test-issue.mjs
import { readFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { SignJWT, importPKCS8 } from "jose";

const __dirname = dirname(fileURLToPath(import.meta.url));
const envText = await readFile(join(__dirname, "..", ".env.local"), "utf8");
for (const line of envText.split("\n")) {
  const m = line.match(/^\s*([A-Z_][A-Z0-9_]*)\s*=\s*(.*)\s*$/);
  if (!m) continue;
  process.env[m[1]] = m[2].replace(/^["']|["']$/g, "");
}

const INSTALLATION_ID = Number(process.argv[2] ?? 147710739);
const REPO = process.argv[3] ?? "akushonkamen/gitautodev-deploy-smoke-1784474393";

const pem = Buffer.from(process.env.APP_PRIVATE_KEY, "base64").toString("utf-8");
const key = await importPKCS8(pem, "RS256");
const now = Math.floor(Date.now() / 1000);
const jwt = await new SignJWT({}).setProtectedHeader({ alg: "RS256" })
  .setIssuer(process.env.APP_ID).setIssuedAt(now).setExpirationTime(now + 9 * 60).sign(key);

const mint = await fetch(`https://api.github.com/app/installations/${INSTALLATION_ID}/access_tokens`, {
  method: "POST",
  headers: { Authorization: `Bearer ${jwt}`, Accept: "application/vnd.github+json" },
});
const { token } = await mint.json();
const H = {
  Authorization: `Bearer ${token}`,
  Accept: "application/vnd.github+json",
  "X-GitHub-Api-Version": "2022-11-28",
  "User-Agent": "GithubAutoDev-SmokeTest",
};

const ts = new Date().toISOString().replace(/[:.]/g, "-").slice(0, 19);
const title = `[smoke] triage pipeline check ${ts}`;
const body = `### Summary

Smoke test issue to verify the triage pipeline fires end-to-end after Deploy Wizard.

**Expected**: on issue open, \`triage-issue.yml\` runs, applies \`triage\` label, optionally adds \`accepted-by-claude\` for trivial/standard workload.

### Workload class

\`\`\`
class: trivial
\`\`\`

### Acceptance

- [ ] triage workflow triggered within 30s
- [ ] issue labeled with \`triage\`
- [ ] (optional) comment posted by pipeline with classification

---
auto-generated by scripts/trigger-test-issue.mjs`;

console.log(`Creating issue in ${REPO}...`);
const issueRes = await fetch(`https://api.github.com/repos/${REPO}/issues`, {
  method: "POST",
  headers: H,
  body: JSON.stringify({ title, body, labels: [] }),
});
if (!issueRes.ok) {
  console.error(`Create issue HTTP ${issueRes.status}: ${await issueRes.text()}`);
  process.exit(1);
}
const issue = await issueRes.json();
console.log(`✅ Issue #${issue.number}: ${issue.html_url}`);

console.log(`\nWaiting 20s for workflow to trigger...`);
await new Promise((r) => setTimeout(r, 20000));

console.log(`Fetching recent workflow runs...`);
const runsRes = await fetch(`https://api.github.com/repos/${REPO}/actions/runs?per_page=5`, { headers: H });
const runs = await runsRes.json();
const recent = (runs.workflow_runs ?? []).slice(0, 5);
if (recent.length === 0) {
  console.log("⚠️  No workflow runs found in repo history.");
} else {
  console.log(`\nLast ${recent.length} runs:`);
  for (const r of recent) {
    const age = Math.round((Date.now() - new Date(r.created_at)) / 1000);
    console.log(`  - [${r.status}/${r.conclusion ?? "-"}] ${r.name}  (${age}s ago)`);
    console.log(`    ${r.html_url}`);
  }
}

console.log(`\nIssue: ${issue.html_url}`);
console.log(`Watch runs: https://github.com/${REPO}/actions`);
